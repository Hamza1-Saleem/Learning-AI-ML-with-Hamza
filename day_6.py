def true_label(path):
    parts = [s.lower() for s in path.replace("\\", "/").split("/")[-2:]]
    for s in reversed(parts):
        if "blur" in s: return "blurry"
        if "sharp" in s: return "sharp"
    return ""


def predict_folder(folder):
    folder = (folder or "").strip().strip('"')
    if not os.path.isdir(folder):
        return [], f"Folder not found: `{folder}`", []
    files = sorted(os.path.join(r, f) for r, _, fs in os.walk(folder) for f in fs if f.lower().endswith(IMG_EXT))
    if not files:
        return [], "No images in that folder.", []
    rows, gallery, right, known = [], [], 0, 0
    for p in files:
        try:
            img = Image.open(p)
            pr = probs_for(img)
        except Exception as e:
            rows.append([os.path.relpath(p, folder), "error", "", "", str(e)[:40]]); continue
        k = int(pr.argmax()); lab = CLASSES[k]; t = true_label(p)
        ok = "" if not t else ("✓" if t == lab else "✗")
        if t: known += 1; right += t == lab
        rows.append([os.path.relpath(p, folder), lab, f"{pr[k]:.0%}", t, ok])
        if len(gallery) < 60: gallery.append((p, f"{lab} {pr[k]:.0%} {ok}"))
    n_sharp = sum(r[1] == "sharp" for r in rows)
    summary = f"**{len(rows)} images** → {n_sharp} sharp, {sum(r[1] == 'blurry' for r in rows)} blurry"
    if known:
        summary += f"  \n**Accuracy: {right}/{known} = {right / known:.1%}** (true labels from file or folder names)"
        summary += "  \n_If these images were also used for training, this number is too optimistic._"
    return rows, summary, gallery


