IMG_EXT = (".jpg", ".jpeg", ".png", ".bmp", ".webp", ".tif", ".tiff")
CLASSES = ["blurry", "sharp"]
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
NORM = transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
random.seed(SEED); np.random.seed(SEED); torch.manual_seed(SEED)


def images_in(folder):
    if not os.path.isdir(folder):
        raise SystemExit(f"Folder not found: {folder}\nCheck the path in SETTINGS (spelling, spaces, capitals).")
    return sorted(os.path.join(r, f) for r, _, fs in os.walk(folder) for f in fs
                  if f.lower().endswith(IMG_EXT) and not f.startswith("."))


def stratified(items, frac, rng):
    a, b = [], []
    for c in CLASSES:
        g = [it for it in items if it[1] == c]; rng.shuffle(g)
        k = max(1, round(len(g) * frac)); b += g[:k]; a += g[k:]
    return a, b


def resize_short(img, size):
    s = size / min(img.size)
    return img.resize((max(size, round(img.width * s)), max(size, round(img.height * s))), Image.BILINEAR)


# Augment with flips / crops / colour only — NO resizing or blurring, that would change the label.
train_tf = transforms.Compose([
    transforms.Lambda(lambda im: resize_short(im, IMG_SIZE)),
    transforms.RandomCrop(224), transforms.RandomHorizontalFlip(), transforms.RandomVerticalFlip(),
    transforms.ColorJitter(0.2, 0.2, 0.2), transforms.ToTensor(), NORM])
eval_tf = transforms.Compose([
    transforms.Lambda(lambda im: resize_short(im, IMG_SIZE)),
    transforms.FiveCrop(224),   # 4 corners + centre, predictions averaged
    transforms.Lambda(lambda cs: torch.stack([NORM(transforms.functional.to_tensor(c)) for c in cs]))])


class ImgDS(Dataset):
    def __init__(self, items, tf): self.items, self.tf = items, tf
    def __len__(self): return len(self.items)
    def __getitem__(self, i):
        p, c = self.items[i]
        return self.tf(Image.open(p).convert("RGB")), CLASSES.index(c)


def build_model(pretrained=True):
    def make(pre):
        if ARCH == "resnet18":
            m = models.resnet18(weights=models.ResNet18_Weights.DEFAULT if pre else None); m.fc = nn.Linear(m.fc.in_features, 2)
        elif ARCH == "resnet50":
            m = models.resnet50(weights=models.ResNet50_Weights.DEFAULT if pre else None); m.fc = nn.Linear(m.fc.in_features, 2)
        else:
            m = models.efficientnet_b0(weights=models.EfficientNet_B0_Weights.DEFAULT if pre else None)
            m.classifier[1] = nn.Linear(m.classifier[1].in_features, 2)
        return m
    try:
        m = make(pretrained)
    except Exception as e:
        print("  ! pretrained weights unavailable, training from scratch:", str(e)[:80]); m = make(False)
    return m.to(DEVICE)


@torch.no_grad()
def predict_probs(model, items):
    """P(each class) per image, averaged over 5 crops."""
    model.eval(); out = []
    for x, _ in DataLoader(ImgDS(items, eval_tf), batch_size=16, num_workers=2):
        b = x.shape[0]
        out.append(torch.softmax(model(x.view(-1, *x.shape[2:]).to(DEVICE)), 1).view(b, 5, -1).mean(1).cpu())
    return torch.cat(out)


def report(items, probs, title):
    y = torch.tensor([CLASSES.index(c) for _, c in items]); pred = probs.argmax(1)
    cm = np.zeros((2, 2), int)
    for t, p in zip(y.tolist(), pred.tolist()): cm[t, p] += 1
    acc = (pred == y).float().mean().item()
    print(f"  {title}: accuracy {acc:.1%} ({int((pred == y).sum())}/{len(y)})")
    print(f"                 predicted blurry | predicted sharp")
    print(f"    true blurry  {cm[0, 0]:16d} | {cm[0, 1]:15d}")
    print(f"    true sharp   {cm[1, 0]:16d} | {cm[1, 1]:15d}")
    return acc, cm


def label_from_name(path):
    n = os.path.basename(path).lower()
    if "blur" in n: return "blurry"
    if "sharp" in n: return "sharp"
    return None


# ================================ 1. LOAD + SPLIT =============================================
print(f"Device: {DEVICE}" + ("" if DEVICE == "cuda" else "  (slow — choose Runtime -> T4 GPU)"))
os.makedirs(OUT_DIR, exist_ok=True)
items = [(p, "sharp") for p in images_in(SHARP_DIR)] + [(p, "blurry") for p in images_in(BLURRY_DIR)]
mix_files = images_in(MIX_DIR)
print(f"Found: {sum(c == 'sharp' for _, c in items)} sharp, {sum(c == 'blurry' for _, c in items)} blurry, {len(mix_files)} in mix")

mix_names = {os.path.basename(p) for p in mix_files}
overlap = sum(os.path.basename(p) in mix_names for p, _ in items)
if EXCLUDE_MIX_FROM_TRAINING and overlap:
    kept = [(p, c) for p, c in items if os.path.basename(p) not in mix_names]
    if len(kept) >= 20 and len({c for _, c in kept}) == 2:
        items = kept
        print(f"  removed {overlap} images that also appear in mix/ (so the mix test is fair)")
    else:
        print(f"  NOTE: mix/ contains {overlap} of the same images as sharp/ + blurry/, so they can't be left out.\n"
              f"        Training on them anyway. The honest score is the TEST split and the 'unseen' mix score below.")
if len(items) < 10:
    raise SystemExit("Too few training images. Check SHARP_DIR / BLURRY_DIR.")

rng = random.Random(SEED)
rest, test = stratified(items, TEST_FRAC, rng)
train, val = stratified(rest, VAL_FRAC / (1 - TEST_FRAC), rng)
for name, part in [("train", train), ("val", val), ("test", test)]:
    print(f"  {name:5s}: {len(part):4d} images {dict(Counter(c for _, c in part))}")
with open(f"{OUT_DIR}/split.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["file", "class", "split"])
    for name, part in [("train", train), ("val", val), ("test", test)]: w.writerows([(p, c, name) for p, c in part])

# ================================ 2. TRAIN ====================================================
print(f"\nTraining {ARCH} ...")
model = build_model()
counts = Counter(c for _, c in train)
loss_fn = nn.CrossEntropyLoss(weight=torch.tensor([len(train) / (2 * counts[c]) for c in CLASSES], device=DEVICE),
                              label_smoothing=0.05)
opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=1e-4)
dl = DataLoader(ImgDS(train, train_tf), batch_size=BATCH, shuffle=True, num_workers=2)
sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=LR, total_steps=EPOCHS * len(dl))
scaler = torch.amp.GradScaler(enabled=DEVICE == "cuda")
CKPT = f"{OUT_DIR}/blur_model.pt"
best, bad, history = -1.0, 0, []
for ep in range(1, EPOCHS + 1):
    model.train(); tot, n, t0 = 0.0, 0, time.time()
    for x, y in dl:
        x, y = x.to(DEVICE), y.to(DEVICE)
        opt.zero_grad(set_to_none=True)
        with torch.autocast(DEVICE, enabled=DEVICE == "cuda"):
            loss = loss_fn(model(x), y)
        scaler.scale(loss).backward(); scaler.step(opt); scaler.update(); sched.step()
        tot += loss.item() * len(y); n += len(y)
    vp = predict_probs(model, val)
    va = (vp.argmax(1) == torch.tensor([CLASSES.index(c) for _, c in val])).float().mean().item()
    history.append((tot / n, va)); msg = ""
    if va > best:
        best, bad, msg = va, 0, "  <- best, saved"
        torch.save({"state": model.state_dict(), "classes": CLASSES, "arch": ARCH, "img_size": IMG_SIZE}, CKPT)
    else:
        bad += 1
    print(f"  epoch {ep:2d}/{EPOCHS} | train loss {tot / n:.3f} | val acc {va:.1%} | {time.time() - t0:.0f}s{msg}")
    if bad >= PATIENCE:
        print(f"  early stop (no improvement for {PATIENCE} epochs)"); break

# ================================ 3. TEST SPLIT ===============================================
model.load_state_dict(torch.load(CKPT, map_location=DEVICE)["state"])
print("\nHeld-out test split (never used in training):")
test_acc, test_cm = report(test, predict_probs(model, test), "TEST")

# ================================ 4. YOUR MIX FOLDER ==========================================
print(f"\nPredicting your mix folder: {MIX_DIR}")
mix_items = [(p, "sharp") for p in mix_files]          # label is a placeholder; not used for predicting
mp = predict_probs(model, mix_items)
sorted_dir = f"{OUT_DIR}/mix_sorted"
shutil.rmtree(sorted_dir, ignore_errors=True)
rows = []
for (p, _), pr in zip(mix_items, mp):
    k = int(pr.argmax()); lab = CLASSES[k]
    rows.append([os.path.basename(p), lab, f"{pr[k]:.3f}", f"{pr[1]:.3f}", label_from_name(p) or ""])
    os.makedirs(f"{sorted_dir}/{lab}", exist_ok=True); shutil.copy(p, f"{sorted_dir}/{lab}/{os.path.basename(p)}")
with open(f"{OUT_DIR}/mix_predictions.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["file", "prediction", "confidence", "p_sharp", "label_from_filename"]); w.writerows(rows)
print(f"  {len(rows)} images -> {dict(Counter(r[1] for r in rows))}")

# If the file names say sharp/blur (e.g. coffee_0_blurry.png), score the mix too
named = [(p, label_from_name(p)) for p in mix_files]
if named and all(l for _, l in named):
    report(named, mp, "MIX, all images (true labels taken from file names)")
    seen = {os.path.basename(p) for p, _ in train + val}
    unseen = [i for i, (p, _) in enumerate(named) if os.path.basename(p) not in seen]
    if len(unseen) < len(named) and unseen:
        print(f"  ({len(named) - len(unseen)} mix images were used in training, so that score is too optimistic)")
        report([named[i] for i in unseen], mp[unseen], "MIX, only images the model never trained on")

json.dump({"test_accuracy": test_acc, "best_val_accuracy": best, "test_confusion": test_cm.tolist(),
           "history": history}, open(f"{OUT_DIR}/results.json", "w"), indent=2)

