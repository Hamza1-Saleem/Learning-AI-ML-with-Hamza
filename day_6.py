def resize_short(img, size):
    s = size / min(img.size)
    return img.resize((max(size, round(img.width * s)), max(size, round(img.height * s))), Image.BILINEAR)


five_crop = transforms.Compose([
    transforms.FiveCrop(224),
    transforms.Lambda(lambda cs: torch.stack([NORM(transforms.functional.to_tensor(c)) for c in cs]))])
centre = transforms.Compose([transforms.CenterCrop(224), transforms.ToTensor(), NORM])


@torch.no_grad()
def probs_for(img, fast=False):
    """Class probabilities for one PIL image. fast=True uses 1 crop (for live video)."""
    img = resize_short(img.convert("RGB"), IMG_SIZE)
    if fast:
        return torch.softmax(model(centre(img).unsqueeze(0).to(DEVICE)), 1)[0].cpu()
    return torch.softmax(model(five_crop(img).to(DEVICE)), 1).mean(0).cpu()


def edge_score(img):
    """Classic non-ML sharpness score (variance of the Laplacian) for comparison."""
    g = np.asarray(resize_short(img.convert("L"), IMG_SIZE), float) / 255
    return float(ndimage.laplace(g).var())


def verdict_md(p):
    k = int(p.argmax()); lab, conf = CLASSES[k], float(p[k])
    colour = "#1a7f37" if lab == "sharp" else "#cf222e"
    note = "" if conf >= 0.75 else "  \n_Low confidence: the model isn't sure about this one._"
    return f"<h2 style='color:{colour};margin:0'>{lab.upper()}</h2>Confidence: **{conf:.0%}**{note}"


# ---------------- tab 1: single photo ----------------
def predict_photo(img):
    if img is None:
        return {}, "Upload, snap or paste an image first.", ""
    p = probs_for(img)
    es = edge_score(img)
    return ({c: float(v) for c, v in zip(CLASSES, p)}, verdict_md(p),
            f"Image size {img.width}×{img.height}px · edge-detail score (variance of Laplacian): {es:.5f}  "
            f"(higher = more fine detail; the baseline threshold on your dataset was about 0.00064)")


